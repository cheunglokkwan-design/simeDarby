// How stable is the top 10 when each assumption moves ±20 %? Writes docs/sensitivity.md.
// Usage: npm run sensitivity
import { writeFile } from 'node:fs/promises';
import { DEFAULT_ASSUMPTIONS } from '../src/solar.js';
import { TOWNSHIPS, loadTownship, prepare, rank } from './lib/rank.mjs';

const PARAMS = [
  ['specificYield', 'Specific yield'], ['panelDensity', 'Panel density'],
  ['tariffCommercial', 'Commercial tariff'], ['tariffIndustrial', 'Industrial tariff'], ['tariffResidential', 'Residential tariff'],
  ['exportRate', 'Export credit'], ['capexSmall', 'CAPEX < 50 kWp'], ['capexLarge', 'CAPEX ≥ 50 kWp'],
  ['wGeneration', 'Weight: generation'], ['wSelfUse', 'Weight: self-consumption'], ['wPayback', 'Weight: payback'], ['wShading', 'Weight: sun exposure']
];
const top10 = (ranked) => new Set(ranked.slice(0, 10).map((s) => s.id));
const overlap = (a, b) => [...a].filter((x) => b.has(x)).length;

const lines = [
  '# Sensitivity of the top 10',
  '',
  'Generated by `npm run sensitivity` with the app\'s own scoring and shading code.',
  'Each assumption is moved by −20 % and +20 % on its own; the cell shows how many of the',
  'baseline top-10 sites are still in the top 10 (10/10 = unchanged).',
  ''
];
const summary = [];
for (const [id, t] of Object.entries(TOWNSHIPS)) {
  const sites = prepare(await loadTownship(id));
  const base = top10(rank(sites));
  lines.push(`## ${t.name}`, '', '| Assumption | −20 % | +20 % |', '|---|---|---|');
  let worst = 10;
  for (const [k, label] of PARAMS) {
    const cells = [0.8, 1.2].map((f) => overlap(base, top10(rank(sites, { ...DEFAULT_ASSUMPTIONS, [k]: DEFAULT_ASSUMPTIONS[k] * f }))));
    worst = Math.min(worst, ...cells);
    lines.push(`| ${label} | ${cells[0]}/10 | ${cells[1]}/10 |`);
  }
  const allTariffs = [0.8, 1.2].map((f) =>
    overlap(base, top10(rank(sites, {
      ...DEFAULT_ASSUMPTIONS,
      tariffCommercial: DEFAULT_ASSUMPTIONS.tariffCommercial * f,
      tariffIndustrial: DEFAULT_ASSUMPTIONS.tariffIndustrial * f,
      tariffResidential: DEFAULT_ASSUMPTIONS.tariffResidential * f
    })))
  );
  worst = Math.min(worst, ...allTariffs);
  lines.push(`| All tariffs together | ${allTariffs[0]}/10 | ${allTariffs[1]}/10 |`, '');
  summary.push(`${t.name}: at least ${worst}/10 of the top 10 survive any single ±20 % change`);
  console.log(summary.at(-1));
}
lines.splice(6, 0, '**Summary:** ' + summary.join('; ') + '.', '');
await writeFile(new URL('../docs/sensitivity.md', import.meta.url), lines.join('\n'));
console.log('wrote docs/sensitivity.md');
